import { test, expect } from '@playwright/test';
import { writeFile, readFile, utimes, mkdir, rename, open, unlink } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { samplePdf, samplePng } from './fixtures.mjs';

test.describe.configure({ mode: 'serial' });
const inbox = () => resolve(process.env.INBOX_TEST_RUNTIME, 'inbox');
const login = async (page, username = 'testadmin', password = process.env.INBOX_TEST_PASSWORD) => {
    await page.goto('/Login');
    await page.getByLabel('Nama pengguna', { exact: true }).fill(username);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Masuk', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Dokumen bersama', exact: true })).toBeVisible();
};
const list = async page => (await page.request.get('/api/documents')).json();
async function put(name, bytes) {
    const temporary = resolve(inbox(), `${name}.partial`);
    const destination = resolve(inbox(), name);
    await writeFile(temporary, bytes);
    await rename(temporary, destination);
    const old = new Date(Date.now() - 15000);
    await utimes(destination, old, old);
    return destination;
}

