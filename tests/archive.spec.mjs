test('imports stable files, ignores partial/invalid/oversized files and preserves originals', async ({ page }) => {
    await login(page);
    await writeFile(resolve(inbox(), 'belum-selesai.pdf.partial'), samplePdf());
    await put('bukan-pdf.pdf', Buffer.from('<html>not a document</html>'));
    await put('terlalu-besar.pdf', Buffer.concat([samplePdf(), Buffer.alloc(1100000)]));
    const lockedPath = resolve(inbox(), 'masih-ditulis.pdf');
    const locked = await open(lockedPath, 'w');
    await locked.write(samplePdf());
    const old = new Date(Date.now() - 15000);
    await utimes(lockedPath, old, old);
    await page.waitForTimeout(5000);
    expect((await list(page)).total).toBe(0);
    await locked.close();
    const original = await put('contoh & anggaran.pdf', samplePdf());
    await put('contoh-gambar.png', samplePng());
    await put('contoh-rusak.pdf', Buffer.from('%PDF-this-is-intentionally-broken'));
    await expect.poll(async () => (await list(page)).total).toBe(4);
    await expect.poll(async () => (await list(page)).import.skipped).toBeGreaterThanOrEqual(2);
    expect(await readFile(original)).toEqual(samplePdf());
    const before = await list(page);
    const bytes = await readFile(original);
    await writeFile(original, bytes);
    await utimes(original, old, old);
    await page.waitForTimeout(5000);
    expect((await list(page)).total).toBe(before.total);
    const doc = before.documents.find(doc => doc.name === 'contoh & anggaran.pdf');
    expect(doc.importedUtc).toMatch(/Z$/);
    expect(doc.sourceModifiedUtc).toMatch(/Z$/);
    const content = await page.request.get(`/documents/${doc.id}/content?download=true`);
    expect(content.status()).toBe(200);
    expect(content.headers()['content-disposition']).toContain('attachment');
    expect(createHash('sha256').update(await content.body()).digest('hex')).toBe(createHash('sha256').update(samplePdf()).digest('hex'));
    const range = await page.request.get(`/documents/${doc.id}/content`, { headers: { Range: 'bytes=0-4' } });
    expect(range.status()).toBe(206);
    expect(await range.text()).toBe('%PDF-');
    expect((await page.request.get('/runtime/data/scan-inbox.db')).status()).toBe(404);
    await unlink(original);
    expect((await page.request.get(`/documents/${doc.id}/content`)).status()).toBe(200);
});

