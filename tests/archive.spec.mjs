test('missing inbox warning is visible while archived documents remain available', async ({ page }) => {
    await login(page);
    const source = inbox();
    const destination = source + '-offline';
    await rename(source, destination);
    try {
        await expect.poll(async () => (await list(page)).import.state).toBe('missing');
        await page.getByRole('button', { name: 'Perbarui', exact: true }).click();
        await expect(page.locator('#import-warning')).toContainText('Folder masuk belum tersedia');
        expect((await list(page)).total).toBe(27);
    } finally { await rename(destination, source); }
});
